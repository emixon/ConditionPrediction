function plot_model(x, labels, model_func)
	x_surf1 = -1.3:0.05:1.3
	y_surf1 = -1.3:0.05:1.3
	nx = length(x_surf1)
	ny = length(y_surf1)
	x_surf = ones(nx) * x_surf1'
	y_surf = y_surf1 * ones(ny)'
	preds = reshape(
		model_func(vcat(reshape(x_surf,:)', reshape(y_surf,:)')),
		ny, nx)
	heatmap(x_surf1, y_surf1, preds, c=cgrad([:cyan, :white, :magenta]),
		alpha=0.2, clims=(0,1), xlabel="x₁", ylabel="x₂")

	colors = [:cyan, :magenta][labels .+ 1]
	scatter!(x[1,:], x[2,:], c=colors, lab=:none)

	y_pred = model_func(x)[:]
	acc = mean(Int.(round.(y_pred)) .== labels)
	title!("Accuracy = $(Int(round(acc*100)))%")
end

