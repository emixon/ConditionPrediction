md"""
## Linear regression ↣ neural networks

If you recall, if you have a dataset with $$o$$ observations and $$v$$ independent variables, linear regression can be represented as

``` math
ŷ = m × x + b
```

where x is a $$v \times o$$ matrix (remember that we're using column-major data today), $$m$$ is a $$1 \times v$$ matrix, and $$b$$ is a scalar value. If we carry out that computation, we end up with a $$1 \times o$$ matrix (or a vector, if you prefer) $$\hat{y}$$.

A single layer in a neural network is very similar. It is represented as

``` math
ŷ = w × x + b
```

where $$x$$ is the same as above, $$w$$ (the layer *weights*) is an $$h \times v$$ matrix, where $$h$$ is the desired output dimension of the layer (more on that below), and $$b$$ (the layer *biases*) is a vector of length $$h$$.

So really the only difference between a multiple linear regression and a neural network layer is that the neural network layer can optionally output an $$h \times o$$ matrix rather than a $$1 \times o$$ matrix.

This capability can be used to combine multiple layers together, using the output from one layer as the input to the next. The output dimension $$h$$ of each layer is often referred to as the number of "nodes" or "neurons" in that layer. Usually there will be an "input" layer that directly receives the input data, an "output" layer that has a value of $$h$$ equal to the number of dependent variables you want to predict, and several "hidden" layers in between. This gives rise to this diagram that you have probably seen before, in one form or another:

![neural network](https://media.geeksforgeeks.org/wp-content/cdn-uploads/20230602113310/Neural-Networks-Architecture.png)

"""

# ╔═╡ 74b632fe-7ed4-4090-b073-4d11c1cb3858
md"""
### Exercise 1.1

Create a function named `dense_layer` that takes as arguments a data matrix `x` and a list of parameters `p` and returns the output of the neural network layer described above.

In this function, you can assume that `p` will be a vector containing two items, where the first item is the weight matrix `w` and the second item is the bias vector `b`.

(The term "dense_layer" is used to signify that all of the inputs are connected to all of the outputs, which is in contrast to the "convolutional layers" that we'll learn about later.)

"""

# ╔═╡ 001b69fd-c0fd-4b19-9ad1-b2a60c6da4cf
function dense_layer(x::AbstractMatrix{T}, p::AbstractVector) where T<:AbstractFloat
	w, b = p # Unpack the vector p into the matrix `w` and the vector `b`.
	w * x .+ b
end

# ╔═╡ 3b3d361a-0922-4848-a4fc-8d95f5fb21af
md"""
## Gradient descent with many parameters

So far we have only used gradient descent with a small number of parameters, usually just the values of a single vector β for multiple linear regression. However, for each neural network layer our parameters will need to include a matrix of weights and a vector of biases, and we will need to do gradient descent on all of them at the same time to optimize our model. With multiple neural network layers, that gets to be a lot of parameters to keep track of!

To handle all of these parameters, we will need to update the gradient descent function that we've been using. If you remember, so far to do gradient descent we have been creating a function `e(β)` that calculates the error of our model predictions as a function of parameters `β`, where `β` is a `Vector{Float64}`, and then use the `ForwardDiff` automatic differentiation package to calculate the gradient of `e` with respect to each element in the vector `β`.

Now, what we are going to do instead is to create a function `e(p)` that calculates  the error of our model predictions as a function of parameters `p`, where **`p` is no longer a single `Vector{Float64}`** but is instead now just a `Vector` that can contain different types of items. We will fill the vector `p` with the matrices and vectors holding the weights and biases of our neural network layers.

This won't work with the `ForwardDiff` autodifferentiation library that we have been using, but luckily, there is another autodifferentiation library called `Zygote` which can handle this change just fine. If you remember before we calculated the gradient using `g = e'(β)` where `g` ended up being a Vector{Float64} of the same size as `β`. Similarly, we can do `g = e'(p)` and `g` will end up being a Vector of the same size and type as `p`. So if `p` is a Vector with a matrix of weights and a vector of biases in it (i.e. `[Matrix{Float64}, Vector{Float64}]`), then `g` will have the same form.

Finally, we will also have to change the "update" part of our gradient descent algorithm. Before we updated our parameters using `β .-= η .* g` (where η is the learning rate). It turns out that the same thing works for our new pattern: `p .-= η .* g`.

"""

# ╔═╡ fb1286f0-8b5e-4f83-9749-bfd4416f0ea3
md"""
### Exercise 1.2

Create a many-parameter gradient descent function named `train!` as described above that takes as parameters a model function `modelf` (that itself takes arguments data matrix `x` and parameters `p`), an error function `errf` (that itself takes as arguments vectors `ŷ` and `y`), a vector of parameter objects `p`, a matrix of independent variables `x`, a vector of dependent variables `labels`, a learning rate `η`, and a number of gradient descent steps `nsteps`, and returns model parameters `p` after training.

"""

# ╔═╡ 012d6d19-86f7-4072-90e6-10f263c67c1d
function train!(modelf, errf, p::AbstractVector, x::Matrix{T}, labels::Vector{T}, η::T, nsteps::Int) where T<:AbstractFloat
	# error function
	e(p) = errf(vec(modelf(x, p)), labels)

	# find value of p that minimizes error
	for i in 1:nsteps
		p .= p .- e'(p) .* η
	end

	return p
end

