md"""
### Exercise 1.4b: Binary cross-entropy

The other thing we need to change in our regression model to make it suitable for classification is the loss metric. Instead of MSE, we want to use something called [*binary cross-entropy*](https://en.wikipedia.org/wiki/Cross_entropy). (The "binary" part of the name just means that we have two classes: class 0 and class 1. The statistical meaning of "cross-entropy" is a topic for a more advanced class.)

``` math
\mathrm{BCE} =\ -\frac1N\sum_{n=1}^N\ \bigg[y_n  \log \hat y_n + (1 - y_n)  \log (1 - \hat y_n)\bigg]
```

Create a function `binary_crossentropy` that takes as arguments vector `ŷ` and `y` and returns the binary cross-entropy between them.

Note that because we did $$e^x$$ in the logistic function above, we want to use the natural (base-$$e$$) logarithm here. You can do the natural logarithm in Julia using the function `log(x)`. (The natural log is the default type of logarithm in most computing languages.)
"""

# ╔═╡ 5a0a1ba6-6861-4b07-bfc2-6d8cde77cd68
function binary_crossentropy(ŷ::Vector{T}, y::Vector{T}) where T<:AbstractFloat
	-1/length(y) * sum([y[i]log(ŷ[i]) + (1-y[i])*log(1-ŷ[i]) for i in 1:length(y)])
end

