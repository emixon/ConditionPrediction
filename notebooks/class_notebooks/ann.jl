# ╔═╡ ac4ec075-23f6-4fff-8458-e2ec8c5b09f2
function generate_circles(nsamplesout, nsamplesin, noise, factor)
	range_out = 0:(2π/nsamplesout):2π
    range_in = 0:(2π/nsamplesin):2π
    x = vcat(cos.(range_out)', sin.(range_out)')
    x = hcat(x, vcat(cos.(range_in)' * factor, sin.(range_in)' * factor))
	x .+= rand(Normal(0, noise), size(x))
	labels = zeros(Int, nsamplesout)
	append!(labels, ones(Int, nsamplesin)...)

	return x, labels
end

